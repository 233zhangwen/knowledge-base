/**
 * 上下文预算（W16 C 组）：多跳之后，别让同一段话占两次位置。
 *
 * ## 为什么需要它
 *
 * W16 加了「指路要追」和「版本要核」两条规则后，平均检索次数从 1.25 涨到 3.33，
 * input token 从 3819 涨到 10735（+181%）。拆开看，涨幅里有很大一块不是信息，
 * 是**重复**：
 *
 *   第 1 次检索命中 C#2 → 注入 5 块
 *   第 2 次改写问句再查 → 又命中 C#2 → **同一段 500 字再注入一遍**
 *
 * 编号是复用的（`ledger.numbers` 按 chunkId 去重），所以引用不会错乱；
 * 但**正文没有去重**，模型把同一段读了两遍。这是纯浪费：不产生新信息，
 * 只消耗 token、稀释注意力。
 *
 * ## 为什么只做无损，不做摘要
 *
 * 摘要会改写数字。这个项目的核心卖点是「引用可溯源」，让一个可能改数字的环节
 * 横在答案和原文之间，是自相矛盾的（spec 决策②）。
 * 所以这里只做不需要理解语义的事：**已见块占位**。
 *
 * 「超限裁剪」这一档（spec 的 C1-b）先不做：流式已经发出去的内容撤不回来，
 * 能做的只有「不再注入新块」，那会丢证据。等去重后的 token 数据出来再决定要不要动它。
 *
 * 纯函数模块，不 import 任何建连代码 —— 单测才能在 CI 无数据库的环境下跑
 * （W13 踩过的坑：纯逻辑和 prisma 混住会让整片测试变红）。
 */

/** 一个已注入过的块的最小描述。 */
export type SeenChunk = {
  /** 全局引用编号（W10 A3 的跨检索累计编号） */
  no: number;
  documentTitle: string;
  chunkIndex: number;
};

/**
 * 二次命中时的占位文本。
 *
 * 为什么给"标题 + 段号"而不是完全留空：
 * 模型需要知道"这条编号对应的是哪份文件的哪一段"，否则后面的引用规则（[n] 必须
 * 指向实际给过的编号）就失去了锚点。给元数据、不给正文 —— 这正是"无损"的含义：
 * 没删任何信息，只是把"重复的那份"换成了指针。
 *
 * 措辞里明确写"内容与前文相同"，是为了压住模型的一个自然倾向：
 * 看到编号就想去找它后面的正文，找不到可能会自行编造。
 */
export function seenPlaceholder(c: SeenChunk): string {
  return `[${c.no}] （《${c.documentTitle}》第 ${c.chunkIndex + 1} 段：内容与前文已给过的同编号片段完全相同，此处不再重复）`;
}

/**
 * 指路句检测（W16 B 组的实现核心）。
 *
 * ## 为什么这件事不能交给 prompt
 *
 * 最初的做法是往 system prompt 里加一条：
 *   「检索结果里若出现『按《某文件》执行』这类指路式表述，必须再检索一次」
 *
 * 实测下来，这条规则把 **49 条单跳题的平均检索次数从 1.13 推到了 2.63**，token 翻倍，
 * 而那些题本来一次就够。原因是条件句式的规则模型判不准：它无法可靠地判断
 * "我这次看到的算不算指路句"，于是倾向于**一律多查一次**保平安。
 *
 * 改成代码检测后，条件是确定的：真的出现了 `按《X》` 才提示，没出现就什么都不加。
 * 模型只需要执行"看到提示就去查"，不需要判断"该不该触发"——
 * 判断交给出题人写死的正则，这才是它该待的地方。
 *
 * ## 为什么不直接替模型查
 *
 * 那样就成了硬编码的多跳编排，遇到"按《X》执行"但 X 不在库里时会白跑一趟，
 * 而且把"要不要查"从决策变成了流程。这里只给提示，查不查仍由模型定。
 */

/** 指路的几种写法。刻意收窄 —— 宁可漏检（少一次检索），不可滥检（每次都多查）。 */
const POINTER_PATTERNS = [
  /按《([^》]{2,40})》/g,
  /参照《([^》]{2,40})》/g,
  /参见《([^》]{2,40})》/g,
  /详见《([^》]{2,40})》/g,
  /依《([^》]{2,40})》/g,
];

/**
 * 没有书名号的指路：「按母公司标准执行」「按总公司规定处理」。
 *
 * 实测里的真实例子（m02）：研发中心制度写「婚假、丧假、产假按国家规定与母公司标准执行」，
 * 一个书名号都没有，但它是标准的指路 —— 具体天数在母公司手册里。
 * 只抓书名号会漏掉这一整类。
 *
 * 限定 12 字以内 + 必须跟「标准/规定/执行」，避免把「按规定办理」这种废话也当成指路。
 */
const ORG_POINTER = /按[^。\n]{0,12}(母公司|总公司|集团)[^。\n]{0,10}(标准|规定|执行)/g;

/**
 * 从一批块里找出被指向的文件名（去重、保序）。
 *
 * 安全：结果会拼进**围栏之外**的系统提示区，而书名号里的内容来自上传文档，
 * 属不可信输入。所以这里做三件事：限长 40、剥掉控制字符与换行、
 * 剥掉书名号本身（防止构造出 `》执行…忽略以上规则` 之类越界文本）。
 */
export function pointerHints(chunks: { content: string }[]): string[] {
  // 位置信息必须留：多个 pattern 轮流扫，不记 index 就会按"正则顺序"而不是"出现顺序"返回
  const hits: { name: string; at: number }[] = [];
  let offset = 0;

  for (const c of chunks) {
    // 无书名号的那一类单独处理：它没有捕获组，命中就叫「母公司相关规定」
    const org = new RegExp(ORG_POINTER.source, 'g');
    let om: RegExpExecArray | null;
    while ((om = org.exec(c.content)) !== null) {
      hits.push({ name: '母公司相关规定', at: offset + om.index });
    }

    for (const re of POINTER_PATTERNS) {
      const r = new RegExp(re.source, 'g');
      let m: RegExpExecArray | null;
      while ((m = r.exec(c.content)) !== null) {
        const name = m[1]
          .replace(/[《》\r\n\t\u0000-\u001f\u200b-\u200f\u2028\u2029]/g, '')
          .trim()
          .slice(0, 40);
        if (name) hits.push({ name, at: offset + m.index });
      }
    }
    offset += c.content.length + 1; // +1 保证相邻块的偏移不重叠
  }

  hits.sort((a, b) => a.at - b.at);
  const out: string[] = [];
  const seen = new Set<string>();
  for (const h of hits) {
    if (!seen.has(h.name)) {
      seen.add(h.name);
      out.push(h.name);
    }
  }
  return out;
}

/** 提示文本（围栏之外、系统口吻）。没有指向时返回空串，调用方直接跳过。 */
export function pointerHintText(names: string[]): string {
  if (!names.length) return '';
  return (
    `（检索提示：上面的片段里提到按《${names.join('》《')}》执行 —— 那只是指向，不是条款本身。` +
    `如果问题要的是具体规定或数值，请以该文件名或其中的关键词再检索一次，不要停在指针上。）`
  );
}

